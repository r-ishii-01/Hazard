/**
 * 合成（近似）地形のための地理データ（経度・緯度 [度]、世界測地系）。
 *
 * 【出典・作成方法】
 * - 海岸線と江の島の輪郭: 政府統計の総合窓口（e-Stat）「国勢調査（平成27年）小地域（町丁・字等別）境界データ」
 *   https://www.e-stat.go.jp/gis/statmap-search?type=2 を GeoJSON 化した Geolonia「japanese-boundaries」
 *   https://github.com/geolonia/japanese-boundaries の藤沢市・鎌倉市・茅ヶ崎市の町丁目境界を z15 画素（約 3.9 m）に
 *   ラスタ化し、陸域の輪郭を約 8 m の許容差で単純化して作成（加工）。江の島大橋・江の島弁天橋の区間は橋なので陸から除いた。
 * - 河川の中心線・川幅、丘陵（高台）の範囲と高さの目安: 国土地理院の標高タイル（DEM5A、
 *   https://maps.gsi.go.jp/development/ichiran.html#dem ）を加工して作成。水面（無効値）の連なりから河道の中心線を、
 *   平滑化した標高の 15 m・35 m 等高線から高台の輪郭を求め、平滑化・単純化した（加工）。
 *   高さの目安は各範囲の標高の中央値・上位15%値。
 *
 * いずれも実際の地形の「概略」であり、国土地理院の標高データを取得できないときの代用にのみ使う。
 */


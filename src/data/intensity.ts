import { SHINDO_LABEL } from '../core/types';
import type { ShindoLevel } from '../core/types';

export interface IntensityInfo {
  shindo: ShindoLevel;
  /** 表示名（例: 「震度5弱」） */
  label: string;
  /** 人の体感・行動 */
  person: string;
  /** 屋内の状況 */
  indoor: string;
  /** 屋外の状況 */
  outdoor: string;
  /** 揺れアニメーションの強さ（0〜1）。演出用の設定値 */
  shake: number;
  /** 表示色（気象庁の配色指針。震度0のみ本サイトの設定） */
  color: string;
}

